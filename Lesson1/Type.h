/*
	Cpp에는 기본적으로 여러가지 자료형이 존재한다.
	
	<<자료형>>
	int			4byte 정수만 보관
	float		4byte 실수만 보관
	long		8byte 정수만 보관
	double		8byte 실수만 보관
	short		2byte 메모리 절약과 하드웨어 제어
	char		1byte 문자를 보관하는 것이 가능
	bool		1byte 참거짓을 판단하는 자료형
	void		따로 저장되는 것은 없는 기타 특수 자료형이다

	위에 서술한 자료형을 사용해서 후술할 함수를 작성하는 데에 사용하기도 한다.
*/

/*
	Cpp이 아니여도 여러가지 프로그램 언어들은 비슷한 논리식과 계산 방법을 가지고 있다.
	물론 우리가 현실해서 사용하는 수학적인 식들도 물론 존재한다.
	하지만 프로그램의 언어에서만 사용하는 계산 방법들이 따로 존재한다.
	이번에는 우리는 그 식들에 대해서 배워보겠다.

	'=' : 우리가 보통 수학에서 '='은 두 식은 같다라는 것으로 배웠을 것이다.
		  하지만 컴퓨터 프로그래밍에서 '='는 왼쪽에 있는 항에다 오른쪽에 있는 변수를
		  대입하겠다라는 뜻이 된다.
		  ex) a가 0이라고 치자. a = 1이 쓰여지면 a의 값은 1이 되는 것이다.

	'==' : 위에서 '='는 "오른쪽 항의 데이터를 대입하겠다."라는 뜻을 가지고 있었다.
		   그러면 '양쪽의 변수가 같다.'라는 식도 컴퓨터에서도 있어야한다.
		   이때 우리는 '=='을 사용한다. 
		   참일 때 1이 출력 거짓일 때 0을 출력한다.
		   ex) a와 b의 값이 1이라고 했을 때 'a == b'의 값은 참이므로 1이 출력 된다.
		       a와 b의 값이 서로 다를 때 'a == b'는 서로 다르므로 0이 출력된다.

	'!' : 컴퓨터에서 가끔씩 값을 부정해야 할 때가 필요하다.
		  이때 우리는 '!'을 부정형을 사용할 수 있다.
		  보통 변수의 앞 혹은 식의 앞에서 사용된다.
		  ex) true 값인 변수 a에 !a를 하면 값이 false로 변화한다.
		      a와 b가 서로 다른 식일 때 두 개를 비교해서 출력하는 값이 true여야한다. 그럴려면 'a != b'이어야 true값이 출력된다.

	'&&' : and 연산이다. 비교하는 두 조건이 둘 다 참이여야지 true 값을 출력한다.
		   나머지 조건들은 flase 값을 출력한다.

	'||' : or 연산이다. 비교하는 두 조건이 둘 다 거짓이여야지 false 값을 출력한다.
		   반대로 다른 조건들은 모두 true값을 출력한다.
	
	'o=' : 컴퓨터에서 산술 연산을 할 때마다 특정 데이터에다가 저장해야한다.
		   기존의 프로그래머가 "기존의 데이터에 결과값을 대입하면서 더하는 방법이 없을까?"라는 생각을 하면서
		   효율적인 방법을 만들어 냈다.
		   그것이 대입 연산자이다.
		   대입 연산자에는 '+=', '-=', '*=', '/='. '%='이 존재한다.
		   또 특정 상황에서 자주 쓰는 대입 연산자는 '변수++', '변수--'가 있다.
		   이들은 변수에 각각 1씩 더하거나 빼는 연산이다.
		   ex) 만약 x라는 변수에 5가 들어있을 때, 여기에 3을 더하고 싶다면 보통 아래와 같이 쓴다.
		       x += 3;
*/