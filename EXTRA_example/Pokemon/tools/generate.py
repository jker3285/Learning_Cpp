from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
CACHE = Path(__file__).resolve().parent / 'source'
FILES = 'pokemon pokemon_species pokemon_species_names pokemon_stats pokemon_stats_past pokemon_types pokemon_types_past pokemon_abilities pokemon_abilities_past abilities ability_names moves move_names move_changelog pokemon_moves version_groups pokemon_move_methods type_names'.split()

def load(name):
    with (CACHE / (name + '.csv')).open(encoding='utf-8', newline='') as f:
        return list(csv.DictReader(f))

def emit(path, body, includes=()):
    p = ROOT / path
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text('// Generated by tools/generate.py; do not edit data manually.\n#pragma once\n' + ''.join('#include "' + h + '"\n' for h in includes) + '\nnamespace pokemon {\n' + body + '\n} // namespace pokemon\n', encoding='utf-8-sig')

def string(s):
    # Keep Korean display names readable in both the source and program output.
    return json.dumps(s, ensure_ascii=False)

def names(table, key):
    return {int(r[key]): r['name'] for r in load(table) if r['local_language_id'] == '3'}

def historical(current, past, keys):
    result = {tuple(int(r[k]) for k in keys): r for r in current}
    # Past rows apply through generation_id, inclusive. The closest upper bound wins.
    for r in sorted(past, key=lambda r: -int(r['generation_id'])):
        if int(r['generation_id']) >= 3:
            result[tuple(int(r[k]) for k in keys)] = r
    return result

