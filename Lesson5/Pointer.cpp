/*
	C++ 포인터(Pointer)의 개념과 사용법

	1. 포인터를 배우는 이유
	이전까지의 수업에서는 주로 `int main() { }`이라는 main 함수 내부에서 변수를 선언하고 사용했다.
	하지만 프로그램이 복잡해지면 main 함수뿐만 아니라 여러 함수를 만들어 사용하게 된다.
	그렇다면 main 함수에서 선언한 변수를 다른 함수에 전달하면 어떻게 될까?
	C++에서는 기본적으로 함수에 변수를 전달할 때 **변수에 저장된 값을 복사해서 전달**한다.
	이를 **값에 의한 전달(Call by Value)**이라고 한다.
	이 방식에서는 원본 변수의 값이 아닌 복사된 값을 사용하기 때문에, 다른 함수에서 값을 변경하더라도 main 함수에 있는 원본 변수의 값은 변경되지 않는다.
	그렇다면 다른 함수에서 main 함수에 있는 원본 변수의 값을 직접 변경하려면 어떻게 해야 할까?
	이때 사용할 수 있는 방법 중 하나가 **포인터(Pointer)**이다.
	포인터를 사용하면 변수의 값을 복사해서 전달하는 대신, 변수가 저장된 메모리 주소를 전달하여 해당 변수에 직접 접근할 수 있다.

	2. 포인터란 무엇인가?
	포인터란 **메모리 주소를 저장하는 변수**를 의미한다.
	우리가 택배를 배송하는 상황을 생각해 보자.
	택배를 정확한 목적지에 배송하려면 배송지의 주소를 알아야 한다.
	이때 다음과 같이 비유할 수 있다.

	- **일반 변수:** 물건이 보관된 집
	- **변수에 저장된 값:** 집 안에 있는 물건
	- **메모리 주소:** 집의 주소
	- **포인터 변수:** 집 주소를 기록해 놓은 메모

	예를 들어 `int a = 10;`이라는 변수가 있다고 가정하자.
	이 변수는 메모리의 특정 위치에 저장되며, 그 위치에는 10이라는 값이 들어 있다.
	포인터 변수는 10이라는 값을 직접 저장하는 것이 아니라, **변수 a가 저장된 메모리 주소**를 저장한다.
	따라서 포인터에 저장된 주소를 이용하면 해당 메모리 위치에 접근하여 값을 읽거나 변경할 수 있다.

	## 3. 포인터의 선언과 연산자
	C++에서 포인터를 사용하려면 `*`와 `&` 연산자를 이해해야 한다.
	### 3.1. 포인터 선언: `*`
	포인터 변수는 다음과 같이 선언한다.
	```cpp
	int* ptr;
	```
	여기서 `int*`는 정수형 변수의 주소를 저장하는 포인터 타입이며, `ptr`은 포인터 변수의 이름이다.

	포인터 변수에는 자신이 가리킬 자료형에 맞는 주소를 저장해야 한다.

	### 3.2. 주소 연산자: `&`

	`&`는 변수의 메모리 주소를 가져오는 연산자이다.

	```cpp
	int a = 10;
	int* ptr = &a;
	```

	위 코드에서 `&a`는 변수 a의 메모리 주소를 의미한다.

	따라서 포인터 변수 ptr에는 a의 값인 10이 아니라 a의 메모리 주소가 저장된다.

	### 3.3. 역참조 연산자: `*`

	포인터 변수에 저장된 주소를 이용하여 해당 위치에 있는 값에 접근하는 것을 **역참조(Dereference)**라고 한다.

	```cpp
	int a = 10;
	int* ptr = &a;

	cout << *ptr; // 10 출력
	```

	여기서 `*ptr`은 ptr에 저장된 주소가 가리키는 메모리 위치의 값을 의미한다.

	또한 역참조를 이용하면 원본 변수의 값을 변경할 수도 있다.

	```cpp
	*ptr = 20;
	```

	이렇게 작성하면 ptr이 가리키는 변수 a의 값이 10에서 20으로 변경된다.

	주의할 점은 `*`가 포인터 선언에 사용될 때와 역참조에 사용될 때 의미가 다르다는 것이다.

	## 4. 함수를 사용할 때 포인터가 필요한 이유

	다른 함수에서 원본 변수의 값을 변경해야 하는 상황을 생각해 보자.

	일반적인 값 전달 방식에서는 복사본이 전달되기 때문에 원본 값이 변경되지 않는다.
	
	하지만 포인터를 이용하면 변수의 주소를 전달할 수 있으므로 다른 함수에서도 원본 변수에 접근할 수 있다.
	
	즉, 포인터는 단순히 값을 전달하기 위한 기능이 아니라, **메모리 주소를 이용하여 데이터에 간접적으로 접근하고 조작하기 위한 기능**이다.

	단, C++에서는 포인터뿐만 아니라 참조자(Reference)를 이용해서도 원본 변수를 변경할 수 있다.

	## 5. 정리

	포인터에서 기억해야 할 핵심 개념은 다음과 같다.

	1. 포인터는 메모리 주소를 저장하는 변수이다.
	2. `&`는 변수의 메모리 주소를 가져오는 연산자이다.
	3. `*`는 포인터 선언 또는 역참조에 사용된다.
	4. 포인터를 이용하면 원본 변수의 값을 직접 읽거나 변경할 수 있다.
	5. 함수에 포인터를 전달하면 다른 함수에서도 원본 변수에 접근할 수 있다.

	**포인터의 핵심은 값을 복사하는 것이 아니라, 메모리 주소를 이용하여 원하는 데이터에 접근하는 것이다.**

	
*/
#include <iostream>
using namespace std;

void change(int* num) {
	*num = 100;
}

int main() {

	{
		int a = 10;
		int* ptr = &a;

		cout << "원래 값: " << a << endl;
		cout << "변수의 주소: " << &a << endl;
		cout << "포인터에 저장된 주소: " << ptr << endl;
		cout << "포인터가 가리키는 값: " << *ptr << endl;

		*ptr = 30;

		cout << "변경된 값: " << a << endl;

		return 0;
	}

	{
		int a = 10;

		cout << "함수 호출 전: " << a << endl;

		change(&a);

		cout << "함수 호출 후: " << a << endl;

		return 0;
	}
}