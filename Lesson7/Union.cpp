/*
	구조체를 다뤄봤으니 이번에는 공용체를 다룰 시간이다.
	이전에 설명했듯 구조체는 여러가지 타입의 변수들의 집합체라고 설명했다.
	그에 걸맞듯 각 타입의 용량에 맞게 구조체가 차지하는 메모리 공간에 영향을 준다.

	하지만 공용체는 가장 큰 데이터의 크기를 기준으로 메모리를 할당하는 특징을 가지고 있다.
	이러한 것은 특히 제한된 메모리 공간을 여러 데이터가 공유하여 메모리를 절약하고,
	동일한 메모리 데이터를 다양하게 하는 방법 중 하나이다.

	<<특징>>
	메모리 공간 절약
	- 여러 상태 중 한 번에 하나의 값만 저장하면 되는 상황에서 불필요한 메모리 낭비를 막을 수 있다. 
	주로 램(RAM) 용량이 수 킬로바이트(KB) 수준으로 매우 작은 임베디드 시스템이나 마이크로컨트롤러(MCU) 환경에서 필수적으로 사용된다.


	동일 데이터의 다중 해석 (타입 변환 대체)
	- 메모리에 저장된 비트(Bit) 패턴을 별도의 형변환 연산 없이 다른 자료형으로 즉시 읽어낼 수 있다. 
	예를 들어 4바이트 float 실수의 내부 비트 구조를 int형이나 char 배열로 바로 확인하여 통신 패킷으로 쪼개 보낼 때 매우 유용하다.
	
	하드웨어 레지스터 제어
	- 시스템 프로그래밍에서 특정 하드웨어 레지스터는
	전체 32비트 값으로 한 번에 읽어야 할 때도 있고, 
	내부의 특정 1비트(플래그)만 따로 조작해야 할 때도 있다. 
	공용체 안에 전체 크기 변수와 비트 필드(Bit-field) 구조체를 함께 넣어두면 두 가지 방식 모두 쉽게 접근할 수 있다.

	가변적인 데이터 패킷 처리
	네트워크 통신에서 상황에 따라 다른 형태의 데이터를 담아 보내야 할 때 공용체를 활용한다. 
	패킷의 헤더(Header)에 현재 데이터의 종류를 기록하고, 본문(Payload)을 공용체로 구성하면 
	하나의 패킷 구조로 여러 종류의 메시지를 효율적으로 처리할 수 있다.

	<<주의>>
	공용체는 모든 멤버가 같은 시작 주소를 공유하므로, 
	한 멤버에 새로운 값을 쓰면 기존에 다른 멤버로 저장해 둔 값은 덮어씌워져 손상된다. 
	따라서 현재 공용체에 어떤 타입의 데이터가 들어있는지 
	개발자가 별도의 변수(태그)를 통해 직접 추적하고 관리해야 한다.
*/

#include <iostream>

using namespace std;

union Data {
	int number;
	float decimal;
};

struct StructData {
	int number;
	float decimal;
};

union UnionData {
	int number;
	float decimal;
};

int main()
{
	{
		Data data;

		data.number = 10;
		cout << "정수: " << data.number << '\n';

		data.decimal = 3.14f;
		cout << "실수: " << data.decimal << '\n';

		// 이제 data.number를 읽으면 안 됨.
		// 같은 공간에 decimal을 저장했기 때문.
	}

	{
		// struct: 각 멤버가 별도의 공간을 사용
		StructData s;
		s.number = 10;
		s.decimal = 3.14f;

		cout << "[struct]\n";
		cout << "정수: " << s.number << '\n';   // 10 유지
		cout << "실수: " << s.decimal << '\n';  // 3.14
		cout << "크기: " << sizeof(s) << "바이트\n\n";

		// union: 모든 멤버가 같은 공간을 공유
		UnionData u;
		u.number = 10;

		cout << "[union]\n";
		cout << "정수: " << u.number << '\n';   // 10

		u.decimal = 3.14f;
		cout << "실수: " << u.decimal << '\n';  // 3.14
		// 현재 활성 멤버는 decimal이므로 u.number는 읽지 않는다.

		cout << "크기: " << sizeof(u) << "바이트\n";
	}
}