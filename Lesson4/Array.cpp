/*
	이전 시간 우리는 반복문에 대해서 배웠다.
	이번 시간 우리는 배열에 대해서 배울 것이다.

	보통 우리는 한 가지 변수에는 한 가지의 데이터 밖에 저장하지 못한다고 알고있다.
	하지만 특정 상황에서 여러가지의 데이터를 저장해야하는 상황이 올 경우가 있다.
	이때 우리는 배열이라는 것을 사용하여 한 가지의 변수에 여러가지 데이터를 저장하는 것이 가능하다.

	배열의 구조는 { 0, 1, 2, 3, 4, 5, 6, .... , n - 1, null(char 배열일 경우 생성)` }의 구조를 띈다.
	여기서 "어? 왜 1부터 시작하지 않고 0부터 시작함?" 이라는 의문이 생길 수 있다.
	우리는 흔히 1부터 시작하여 n까지의 수를 저장하는 것으로 인식한다.
	하지만 컴퓨터는 0부터 시작하여 n - 1까지의 수를 저장한다.
	둘 다 n개의 데이터를 저장하는 것은 다르지 않다.
	하지만 우리가 생각하는 것과 다르게 컴퓨터는 1이 아닌 0부터 데이터를 저장하기 시작한다.

	그리고 눈썰미가 좋은 학생들은 배열 마지막에 null이라는 것이 쓰이는 것을 발견 할 수 있을 것이다.
	null은 char타입의 배열을 생성 할 때 생기는 것으로 컴퓨터가 데이터가 끝나는 지점이 어디까지인지 확인하기 위해서 주로 사용하는 것이다.
	만일 우리가 배열의 길이를 알 수 없을 때 배열을 null이 될 때까지 출력하게 하면서 index++을 하면
	배열의 길이를 알 수 있게된다. (굳이 이렇게 안 해도 됨)

	배열은 자료형 변수명[인덱스 크기]로 선언된다.
	인덱스 크기를 선언하면 나중에 인덱스 크기를 변경하고 싶어도 나중에 변경을 할 수 없게 된다.
	후술 할 동적 타입에서는 이 조건이 사라지겠지만 오늘은 정적 배열 타입만 설명하겠다.

	아 그리고 배열을 사용 할 때 반복문을 사용하는 것을 적극적으로 추천한다.
	
	2차원 배열을 사용하면 더욱 여러가지의 일을 할 수 있다.
	예를 들어 기존에 1차원 적으로 저장했던 데이터를 2차원 배열을 사용하면 행 * 열 만큼의 데이터를 더 저장 할 수 있다.
	즉, 기존의 1차원 배열 보다 더 효율적이고 더 많은 데이터를 적은 양 대비 저장 할 수 있다.
	그리고 당연하게도 2차원 적인 일을 할 수 있다.

	<<주의>>
	배열은 꼭 내가 쓰려는 인덱스보다는 크게 잡아야한다.
	그렇지 않으면 마지막 인덱스에서 깨지는 경우가 생긴다.

*/

#include <iostream>

using namespace std;

int main()
{
	{
		cout << "배열에 값을 대입하고 출력하시오." << endl;

		int Array[10] = { 0, }; // { }, { 0 }. { 0, }으로 표기하는 방법은 배열을 초기화 한다고 한다.
		int index = 0;

		while (index < 10)
		{
			cin >> Array[index];

			index++;
		}

		for (index = 0; index < 10; index++)
		{
			cout << Array[index] << " ";
		}

		cout << endl;
	}

	{
		cout << "이차원 배열을 이용하여 구구단을 저장하고 출력하시오." << endl;

		int Array[10][10] = { 0, };

		for (int i = 1; i < 10; i++)
		{
			for (int j = 1; j <= 9; j++)
			{
				Array[i][j] = i * j;
			}
		}

		for (int i = 1; i < 10; i++)
		{
			for (int j = 1; j <= 9; j++)
				cout << i << " * " << j << " = " << Array[i][j] << " ";
			cout << endl;
		}
	}
}